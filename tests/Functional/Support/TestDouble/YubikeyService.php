<?php
declare(strict_types=1);

namespace Surfnet\StepupGateway\Tests\Functional\Support\TestDouble;

use Psr\Log\LoggerInterface;
use ReflectionClass;
use Surfnet\StepupBundle\Exception\InvalidArgumentException;
use Surfnet\StepupBundle\Value\YubikeyOtp;
use Surfnet\StepupGateway\ApiBundle\Dto\Otp as OtpDto;
use Surfnet\StepupGateway\ApiBundle\Dto\Requester;
use Surfnet\StepupGateway\ApiBundle\Service\YubikeyService as GatewayYubikeyService;
use Surfnet\YubikeyApiClient\Service\OtpVerificationResult;
use Surfnet\YubikeyApiClientBundle\Service\VerificationService;

/**
 * Yubikey service for the functional tests: it does not call the Yubico validation service, but accepts any OTP that is
 * well-formed (as if Yubico had validated it).
 *
 * Unlike the Behat test double (ApiBundle\Tests\TestDouble\Service\YubikeyService), it does not replace the check that
 * the OTP was generated by the Yubikey of the user: verifyPublicId() is the one of the Gateway, so the public ID of the
 * OTP must match the identifier of the user's Yubikey. Use otpForPublicId() to generate an OTP for a Yubikey.
 */
final class YubikeyService extends GatewayYubikeyService
{
    public function __construct(LoggerInterface $logger)
    {
        // The Yubico client is only used by verifyOtp(), which is replaced. It is created without its constructor: the
        // real client needs the Yubico client ID and secret, which are not configured in the functional environment.
        $unusedYubicoClient = (new ReflectionClass(VerificationService::class))->newInstanceWithoutConstructor();

        parent::__construct($unusedYubicoClient, $logger);
    }

    public function verifyOtp(OtpDto $otp, Requester $requester)
    {
        try {
            YubikeyOtp::fromString($otp->value);
        } catch (InvalidArgumentException) {
            return new OtpVerificationResult(OtpVerificationResult::ERROR_BAD_OTP);
        }

        return new OtpVerificationResult(OtpVerificationResult::STATUS_OK);
    }

    /**
     * Generate an OTP of the Yubikey with $publicId, the (decimal) second factor identifier of a Yubikey token, e.g.
     * "00000002". The OTP is the modhex encoded public ID, followed by 32 characters of (not really) encrypted data.
     */
    public static function otpForPublicId(string $publicId): string
    {
        $hexadecimalId = str_pad(gmp_strval(gmp_init($publicId, 10), 16), 12, '0', STR_PAD_LEFT);

        return strtr($hexadecimalId, '0123456789abcdef', 'cbdefghijklnrtuv') . str_repeat('c', 32);
    }
}
